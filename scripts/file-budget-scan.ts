/**
 * Measuring the file line budget: which files are in scope, how long each one
 * is, and which are generated rather than hand-written.
 *
 * Split out of ./file-budget.ts so the measurement (a git walk plus file reads)
 * and the ratchet's comparison rules each stay small enough to read. The scope
 * boundaries here are load-bearing: getting one wrong changes what the gate
 * measures, so each is pinned by a test in ./verify-file-budget.spec.ts.
 */

import { execFileSync } from 'node:child_process'
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'

/** Repository-relative path of the ratchet's recorded state. */
export const BASELINE_PATH = 'scripts/file-budget-baseline.json'

/** `Generated by scripts/gen-x.ts` in a file's opening comment. */
const GENERATED_HEADER = /[Gg]enerated by\s+`?([A-Za-z0-9_./-]+\.(?:ts|tsx|mjs|cjs|js))`?/

/** Build-output directory names. Files under `src/` are never build output. */
const BUILD_SEGMENTS = new Set(['node_modules', 'dist', 'dist-test', 'lib', 'build', 'coverage', '.next', '.desktop-build'])

/**
 * Snapshot, backup and scratch directory names this tree carries alongside real
 * source. `refactor-snapshots` holds the pre-split copies a refactor takes; a
 * copy of an oversized file is not an oversized file.
 */
const BACKUP_DIR = /^(?:[^/]*\.bak[^/]*|app-backup-[^/]*|\.gray-backup-[^/]*|refactor-snapshots)$/

/** One measured source file. */
export interface MeasuredFile {
  /** Repository-relative path with forward slashes. */
  path: string
  /** Line count, counting a final unterminated line. */
  lines: number
  /** The generator named in the file's header, or null for hand-written files. */
  generator: string | null
}

/** The recorded state the ratchet compares against. */
export interface FileBudgetBaseline {
  /** Generated files, with the script that writes each one. */
  generated: { path: string; generator: string }[]
  /** Files still over budget, mapped to the line count they are allowed. */
  grandfathered: Record<string, number>
}

/**
 * Whether a tracked path is out of the budget's scope.
 *
 * The scope is "source a person maintains here". Three boundaries decide it,
 * and each one is pinned by a test because getting any of them wrong changes
 * what the gate measures:
 *
 *   - `node_modules` is never in scope, even when the package tree below it has
 *     a `src/` directory — a bundled dependency tree under
 *     `apps/desktop/resources/**` looks exactly like hand-written source.
 *   - A build-output directory is out of scope only when it appears BEFORE a
 *     `src/` segment. `packages/x/lib/a.ts` is build output; `packages/x/src/lib/a.ts`
 *     is a directory that happens to be called `lib`.
 *   - Backup and snapshot copies of real source are out of scope.
 * @param relPath - repository-relative path with forward slashes.
 * @returns true when the file is not hand-written source this repository owns.
 */
export function isOutOfScope(relPath: string): boolean {
  const parts = relPath.split('/')
  const dirs = parts.slice(0, -1)
  if (/\.min\./.test(parts[parts.length - 1] ?? '')) return true
  if (dirs.includes('node_modules')) return true
  if (dirs.some((d) => BACKUP_DIR.test(d))) return true
  const sourceAt = dirs.indexOf('src')
  const leading = sourceAt === -1 ? dirs : dirs.slice(0, sourceAt)
  return leading.some((d) => BUILD_SEGMENTS.has(d))
}

/**
 * Count lines in a source text, treating a final unterminated line as a line.
 * @param text - the file's contents.
 * @returns the line count, matching `wc -l` for newline-terminated files.
 */
export function countLines(text: string): number {
  let n = 0
  for (let i = 0; i < text.length; i += 1) if (text.charCodeAt(i) === 10) n += 1
  if (text.length > 0 && text.charCodeAt(text.length - 1) !== 10) n += 1
  return n
}

/**
 * The generator named in a file's header, if it declares one.
 * @param text - the file's contents.
 * @returns the generator script path, or null when the file is hand-written.
 */
export function generatorFor(text: string): string | null {
  // The banner must be at the TOP of the file. A wider window matched a module
  // that merely EMITS a generator banner as a string constant, which exempted a
  // hand-written file from the budget; every real generated file carries the
  // marker in its first two lines.
  const head = text.split('\n', 3).join('\n')
  return head.match(GENERATED_HEADER)?.[1] ?? null
}

/**
 * Every TypeScript source file in the budget's scope — tracked AND untracked
 * but not ignored. Including untracked files is deliberate: a 5,000-line file
 * is a violation the moment it exists on disk, not the moment someone stages
 * it, and a gate that only sees staged files reports the problem after the
 * author has stopped looking.
 * @param cwd - repository root.
 * @returns repository-relative paths, sorted.
 */
export function listSources(cwd: string): string[] {
  const raw = execFileSync(
    'git',
    ['ls-files', '--cached', '--others', '--exclude-standard', '*.ts', '*.tsx', '*.mts', '*.cts'],
    { cwd, encoding: 'utf8', maxBuffer: 1024 * 1024 * 256 },
  )
  return raw
    .split('\n')
    .map((s) => s.trim())
    .filter((s) => s !== '')
    .filter((s) => !isOutOfScope(s))
    .sort()
}

/**
 * Measure every in-scope source file.
 * @param cwd - repository root.
 * @returns one entry per file, with its line count and generator (if generated).
 */
export function measureBudget(cwd: string): MeasuredFile[] {
  const out: MeasuredFile[] = []
  for (const path of listSources(cwd)) {
    let text: string
    try {
      text = readFileSync(resolve(cwd, path), 'utf8')
    } catch {
      continue // listed but absent from the working tree (deleted in place)
    }
    out.push({ path, lines: countLines(text), generator: generatorFor(text) })
  }
  return out
}

/**
 * Read the recorded ratchet state.
 * @param cwd - repository root.
 * @returns the baseline, with absent sections treated as empty.
 */
export function readBaseline(cwd: string): FileBudgetBaseline {
  const parsed: unknown = JSON.parse(readFileSync(resolve(cwd, BASELINE_PATH), 'utf8'))
  const root = typeof parsed === 'object' && parsed !== null ? (parsed as Record<string, unknown>) : {}
  const generated: FileBudgetBaseline['generated'] = []
  for (const entry of Array.isArray(root['generated']) ? root['generated'] : []) {
    const row = typeof entry === 'object' && entry !== null ? (entry as Record<string, unknown>) : {}
    if (typeof row['path'] === 'string' && typeof row['generator'] === 'string') {
      generated.push({ path: row['path'], generator: row['generator'] })
    }
  }
  const grandfathered: Record<string, number> = {}
  const raw = root['grandfathered']
  for (const [path, value] of Object.entries(typeof raw === 'object' && raw !== null ? raw : {})) {
    if (typeof value === 'number' && Number.isFinite(value)) grandfathered[path] = value
  }
  return { generated, grandfathered }
}
