/**
 * Enforce the 250-line file budget as a one-way ratchet.
 *
 * `scripts/file-budget.ts` owns the measurement and the comparison rules; this
 * file is the command: fail on any new violation, any growth, and any stale
 * baseline entry, and print the generated-file exceptions so each one stays
 * visible with the generator that owns it.
 *
 * `--write` re-records the baseline from the tree as it is now. Run it only
 * after the tree actually improved — it is the ratchet's tightening motion, not
 * a way to accept a regression.
 */

import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import {
  BASELINE_PATH,
  FILE_LINE_BUDGET,
  baselineFrom,
  compareBudget,
  measureBudget,
  readBaseline,
  type BudgetViolation,
} from './file-budget.ts'

const root = resolve(import.meta.dirname, '..')
const write = process.argv.includes('--write')

const measured = measureBudget(root)
if (measured.length < 1000) {
  console.error(
    `verify-file-budget: only ${measured.length} source files found — the corpus is empty or narrowed, refusing to judge it.`,
  )
  process.exit(1)
}

const generated = measured.filter((m) => m.generator !== null)
const over = measured.filter((m) => m.generator === null && m.lines > FILE_LINE_BUDGET)
const worst = [...measured].sort((a, b) => b.lines - a.lines).slice(0, 5)

if (write) {
  const baseline = baselineFrom(measured)
  writeFileSync(resolve(root, BASELINE_PATH), `${JSON.stringify(baseline, null, 2)}\n`)
  console.log(
    `verify-file-budget: recorded ${Object.keys(baseline.grandfathered).length} grandfathered file(s) and ${baseline.generated.length} generated exception(s) to ${BASELINE_PATH}.`,
  )
  process.exit(0)
}

let violations: BudgetViolation[]
try {
  violations = compareBudget(measured, readBaseline(root))
} catch (err) {
  console.error(
    `verify-file-budget: cannot read ${BASELINE_PATH} (${err instanceof Error ? err.message : String(err)}). ` +
      'Run `pnpm run verify-file-budget --write` after confirming the tree really improved.',
  )
  process.exit(1)
}

console.log(
  `verify-file-budget: ${measured.length} source file(s), budget ${FILE_LINE_BUDGET} lines, ` +
    `${over.length} above budget, ${generated.length} generated exception(s).`,
)
for (const g of generated.sort((a, b) => b.lines - a.lines)) {
  console.log(`  excepted  ${String(g.lines).padStart(6)}  ${g.path}  (generated by ${g.generator})`)
}
console.log('  largest: ' + worst.map((w) => `${w.lines} ${w.path}`).join(', '))

if (violations.length === 0) {
  console.log('verify-file-budget: OK — no new over-budget files, no growth, no stale entries.')
  process.exit(0)
}

const order = ['over-budget', 'grew', 'must-lower', 'must-remove'] as const
for (const kind of order) {
  const group = violations.filter((v) => v.kind === kind)
  if (group.length === 0) continue
  console.error(`\n${kind} (${group.length}):`)
  for (const v of group) console.error(`  ${v.file} ${v.message}`)
}
console.error(
  `\nverify-file-budget: ${violations.length} violation(s). Split the file, or — only when the tree genuinely improved — rerecord with --write.`,
)
process.exit(1)
