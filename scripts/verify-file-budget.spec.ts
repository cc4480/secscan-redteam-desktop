/**
 * The file line budget is the gate that stops the tree growing 5,000-line files
 * again, so its detection boundary is pinned here: every form that is admitted
 * or excepted, all four ways the ratchet can slip, and the real corpus checked
 * against its own recorded baseline.
 */

import { describe, expect, it } from 'vitest'
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import {
  FILE_LINE_BUDGET,
  countLines,
  generatorFor,
  isOutOfScope,
  baselineFrom,
  compareBudget,
  measureBudget,
  readBaseline,
  type FileBudgetBaseline,
  type MeasuredFile,
} from './file-budget.ts'

const root = resolve(import.meta.dirname, '..')

const file = (path: string, lines: number, generator: string | null = null): MeasuredFile => ({
  path,
  lines,
  generator,
})

const clean: FileBudgetBaseline = { generated: [], grandfathered: {} }

describe('countLines', () => {
  it('counts a newline-terminated file the way wc -l does', () => {
    expect(countLines('a\nb\nc\n')).toBe(3)
    expect(countLines('')).toBe(0)
  })

  it('counts a final unterminated line', () => {
    expect(countLines('a\nb')).toBe(2)
    expect(countLines('only')).toBe(1)
  })
})

describe('generatorFor', () => {
  it('reads the generator out of a do-not-edit header', () => {
    const head = '/**\n * Generated by scripts/gen-cordis-api.ts — do not edit by hand.\n */\n'
    expect(generatorFor(head)).toBe('scripts/gen-cordis-api.ts')
  })

  it('answers null for hand-written source', () => {
    expect(generatorFor('/** A hand-written module. */\nexport const x = 1\n')).toBeNull()
  })

  it('does not scan the whole file for a late mention', () => {
    const late = ['// heading', ...Array.from({ length: 20 }, () => '// filler'),
      '// Generated by scripts/gen-late.ts', ''].join('\n')
    expect(generatorFor(late)).toBeNull()
  })
})

describe('isOutOfScope', () => {
  it('admits hand-written source wherever it lives', () => {
    expect(isOutOfScope('packages/core/tools/src/index.ts')).toBe(false)
    expect(isOutOfScope('scripts/run-gates.ts')).toBe(false)
    expect(isOutOfScope('apps/web/tests/scaffold.ts')).toBe(false)
    expect(isOutOfScope('snapshots/session/headless.snapshot.ts')).toBe(false)
  })

  it('admits a build-named directory that sits under src', () => {
    expect(isOutOfScope('packages/fs/fs/src/lib/containment.ts')).toBe(false)
    expect(isOutOfScope('packages/core/tools/src/build/emit.ts')).toBe(false)
  })

  it('excludes a build-named directory that precedes src', () => {
    expect(isOutOfScope('packages/core/tools/lib/index.ts')).toBe(true)
  })

  it('excludes build output', () => {
    for (const p of [
      'packages/core/tools/lib/index.js',
      'apps/desktop/resources/redteam-runner/dist/agents.js',
      'packages/redteam/harness-plugin/dist-test/src/auth-gate.js',
      'node_modules/foo/index.ts',
      'apps/web/.next/thing.ts',
      'packages/x/build/out.ts',
      'packages/x/coverage/report.ts',
      'apps/desktop/.desktop-build/development/home/a.ts',
    ]) {
      expect(isOutOfScope(p), p).toBe(true)
    }
  })

  it('excludes a dependency tree even when it contains src/ directories', () => {
    // The bundled runner under apps/desktop/resources ships a node_modules tree
    // whose packages have ordinary src/ folders; none of it is ours to budget.
    expect(
      isOutOfScope('apps/desktop/resources/redteam-runner/node_modules/@deepseek-ai/cosmokit/src/array.ts'),
    ).toBe(true)
    expect(isOutOfScope('apps/desktop/resources/redteam-runner/dist/seclayer/src/types.d.ts')).toBe(true)
  })

  it('excludes snapshot and backup copies of real source', () => {
    expect(isOutOfScope('app-backup-2026-11-07-pre-livingsheen/packages/a.ts')).toBe(true)
    expect(isOutOfScope('.gray-backup-2026-11-08-0310/packages/a.ts')).toBe(true)
    expect(isOutOfScope('packages/redteam/auth-gate/lib.bak-20261108/types/a.js')).toBe(true)
    expect(isOutOfScope('packages/x/src/a.min.ts')).toBe(true)
  })

  it('excludes a refactor snapshot of an oversized file', () => {
    // A copy taken before a split is not a violation: budgeting the copies would
    // make every refactor slice fail the gate it is trying to satisfy.
    expect(isOutOfScope('refactor-snapshots/2026-11-12/W1/core-session/src/index.ts')).toBe(true)
    expect(isOutOfScope('refactor-snapshots/2026-11-12/W2/tools/extract.ts')).toBe(true)
  })
})

describe('compareBudget', () => {
  it('passes a clean tree', () => {
    expect(compareBudget([file('a.ts', 10)], clean)).toEqual([])
  })

  it('fails a file the baseline never saw that is over budget', () => {
    const v = compareBudget([file('a.ts', FILE_LINE_BUDGET + 1)], clean)
    expect(v).toHaveLength(1)
    expect(v[0]?.kind).toBe('over-budget')
  })

  it('passes a file at exactly the budget', () => {
    expect(compareBudget([file('a.ts', FILE_LINE_BUDGET)], clean)).toEqual([])
  })

  it('fails growth past a grandfathered count', () => {
    const base: FileBudgetBaseline = { generated: [], grandfathered: { 'a.ts': 900 } }
    const v = compareBudget([file('a.ts', 901)], base)
    expect(v[0]?.kind).toBe('grew')
    expect(v[0]?.allowed).toBe(900)
  })

  it('accepts a grandfathered file that stayed the same', () => {
    const base: FileBudgetBaseline = { generated: [], grandfathered: { 'a.ts': 900 } }
    expect(compareBudget([file('a.ts', 900)], base)).toEqual([])
  })

  it('fails a stale ceiling when a grandfathered file shrank but is still over budget', () => {
    const base: FileBudgetBaseline = { generated: [], grandfathered: { 'a.ts': 900 } }
    expect(compareBudget([file('a.ts', 500)], base)[0]?.kind).toBe('must-lower')
  })

  it('fails a baseline entry for a file that is now within budget', () => {
    const base: FileBudgetBaseline = { generated: [], grandfathered: { 'a.ts': 900 } }
    expect(compareBudget([file('a.ts', 40)], base)[0]?.kind).toBe('must-remove')
  })

  it('fails a baseline entry whose file is gone', () => {
    const base: FileBudgetBaseline = { generated: [], grandfathered: { 'gone.ts': 900 } }
    expect(compareBudget([], base)[0]?.kind).toBe('must-remove')
  })

  it('excepts generated files by header even when the baseline does not list them', () => {
    expect(compareBudget([file('gen.ts', 9000, 'scripts/gen-x.ts')], clean)).toEqual([])
  })

  it('excepts generated files the baseline lists', () => {
    const base: FileBudgetBaseline = {
      generated: [{ path: 'gen.ts', generator: 'scripts/gen-x.ts' }],
      grandfathered: {},
    }
    expect(compareBudget([file('gen.ts', 9000)], base)).toEqual([])
  })
})

describe('baselineFrom', () => {
  it('round-trips into a baseline that reports no violations', () => {
    const measured = [file('small.ts', 10), file('big.ts', 900), file('gen.ts', 9000, 'scripts/gen.ts')]
    const base = baselineFrom(measured)
    expect(base.grandfathered).toEqual({ 'big.ts': 900 })
    expect(base.generated).toEqual([{ path: 'gen.ts', generator: 'scripts/gen.ts' }])
    expect(compareBudget(measured, base)).toEqual([])
  })
})

describe('the tree', () => {
  // Measuring the whole corpus is a filesystem walk over ~6k files; do it once
  // for the file (outside any test's timeout) and share the result.
  let cached: MeasuredFile[] | undefined
  const measuredOnce = (): MeasuredFile[] => {
    cached ??= measureBudget(root)
    return cached
  }

  it('finds a corpus large enough to judge', { timeout: 120_000 }, () => {
    // A narrowed or empty corpus would make every assertion below vacuous.
    expect(measuredOnce().length).toBeGreaterThan(1000)
  })

  it('holds the budget against its recorded baseline', { timeout: 120_000 }, () => {
    const violations = compareBudget(measuredOnce(), readBaseline(root))
    expect(violations.map((v) => `${v.kind} ${v.file} ${v.message}`)).toEqual([])
  })

  it('records every generated exception with its generator', () => {
    const baseline = readBaseline(root)
    for (const entry of baseline.generated) {
      const text = readFileSync(resolve(root, entry.path), 'utf8')
      expect(generatorFor(text), entry.path).toBe(entry.generator)
    }
  })
})
